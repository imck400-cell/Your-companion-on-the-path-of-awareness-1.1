async function main() {
  console.log('Fetching managers-leaders page...');
  const q = query(collection(db, 'pages'), where('slug', '==', 'managers-leaders'));
  const snapshot = await getDocs(q);
  
  if (snapshot.empty) {
    console.error('Page not found!');
    return;
  }
  
  const pageDoc = snapshot.docs[0];
  let items = pageDoc.data().items || [];
  
  console.log(`Updating item 1: leadership-awareness...`);
  
  const updatedItems = items.map(item => {
    if (item.id === 'leadership-awareness') {
      console.log(`  ✓ Updating: ${item.id}`);
      return {
        ...item,
        content: {
          ...item.content,
          ar: articles['conscious-leadership']
        }
      };
    }
    return item;
  });
  
  await updateDoc(doc(db, 'pages', pageDoc.id), {
    items: updatedItems,
    updatedAt: new Date().toISOString()
  });
  
  console.log('\n✅ Item 1 for Administrators updated successfully!');
}

main().catch(console.error);

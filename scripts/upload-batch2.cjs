async function main() {
  console.log('Fetching managers-leaders page...');
  const q = query(collection(db, 'pages'), where('slug', '==', 'managers-leaders'));
  const snapshot = await getDocs(q);
  
  if (snapshot.empty) {
    console.error('Page not found!');
    return;
  }
  
  const pageDoc = snapshot.docs[0];
  let items = pageDoc.data().items || [];
  
  console.log(`Found ${items.length} items. Updating batch 2 (items 6-10)...`);
  
  // Check if conflict-management exists, if not add it
  if (!items.find(i => i.id === 'conflict-management')) {
    console.log('Adding conflict-management item...');
    items.push({
      id: 'conflict-management',
      title: { ar: 'إدارة الصراعات والنزاعات' },
      content: { ar: '' },
      image: "",
      order: items.length + 1
    });
  }

  const updatedItems = items.map(item => {
    if (articles[item.id]) {
      console.log(`  ✓ Updating: ${item.id}`);
      return {
        ...item,
        content: {
          ...item.content,
          ar: articles[item.id]
        }
      };
    }
    return item;
  });
  
  await updateDoc(doc(db, 'pages', pageDoc.id), {
    items: updatedItems,
    updatedAt: new Date().toISOString()
  });
  
  console.log('\n✅ Batch 2 uploaded successfully!');
}

main().catch(console.error);

async function main() {
  let app;
  try {
    // Try to read firebase config from env
    const response = await fetch('/__firebase_config');
    const config = await response.json();
    app = initializeApp(config);
  } catch (e) {
    // Fallback: read from firebase.json if available
    console.log('Could not fetch firebase config automatically.');
    console.log('Please provide your firebase config manually.');
    process.exit(1);
  }

  const db = getFirestore(app);
  
  console.log('Fetching managers-leaders page from Firestore...');
  
  const q = query(collection(db, 'pages'), where('slug', '==', 'managers-leaders'));
  const snapshot = await getDocs(q);
  
  if (snapshot.empty) {
    console.error('Page "managers-leaders" not found in Firestore!');
    process.exit(1);
  }
  
  const pageDoc = snapshot.docs[0];
  const pageData = pageDoc.data();
  const items = pageData.items || [];
  
  console.log(`Found page with ${items.length} items. Updating article content...`);
  
  const updatedItems = items.map(item => {
    const newContent = ARTICLES[item.id];
    if (newContent) {
      console.log(`✓ Updating content for: ${item.id}`);
      return {
        ...item,
        content: {
          ...item.content,
          ar: newContent
        }
      };
    }
    return item;
  });
  
  await updateDoc(doc(db, 'pages', pageDoc.id), {
    items: updatedItems,
    updatedAt: new Date().toISOString()
  });
  
  console.log('\n✅ All articles uploaded successfully!');
}

main().catch(console.error);

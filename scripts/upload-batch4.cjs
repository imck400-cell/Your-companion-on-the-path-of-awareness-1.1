async function main() {
  console.log('Fetching managers-leaders page...');
  const q = query(collection(db, 'pages'), where('slug', '==', 'managers-leaders'));
  const snapshot = await getDocs(q);
  
  if (snapshot.empty) {
    console.error('Page not found!');
    return;
  }
  
  const pageDoc = snapshot.docs[0];
  let items = pageDoc.data().items || [];
  
  console.log(`Found ${items.length} items. Updating batch 4 (items 16-20)...`);
  
  // Titles for the new items
  const titleMap = {
    'financial-management': 'الإدارة المالية لغير الماليين',
    'digital-transformation': 'التحول الرقمي المدرسي',
    'creative-decisions': 'اتخاذ القرار وحل المشكلات',
    'ethics-governance': 'الأخلاقيات والحوكمة',
    'performance-kpis': 'قياس الأداء والمؤشرات'
  };

  // Ensure items exist
  Object.keys(articles).forEach(id => {
    if (!items.find(i => i.id === id)) {
      console.log(`Adding ${id} item...`);
      items.push({
        id,
        title: { ar: titleMap[id] || id },
        content: { ar: '' },
        image: "",
        order: items.length + 1
      });
    }
  });

  const updatedItems = items.map(item => {
    if (articles[item.id]) {
      console.log(`  ✓ Updating: ${item.id}`);
      return {
        ...item,
        title: {
            ...item.title,
            ar: titleMap[item.id] || item.title?.ar
        },
        content: {
          ...item.content,
          ar: articles[item.id]
        }
      };
    }
    return item;
  });
  
  await updateDoc(doc(db, 'pages', pageDoc.id), {
    items: updatedItems,
    updatedAt: new Date().toISOString()
  });
  
  console.log('\n✅ Batch 4 uploaded successfully!');
}

main().catch(console.error);

async function main() {
  console.log('Fetching companies page...');
  const q = query(collection(db, 'pages'), where('slug', '==', 'companies'));
  const snapshot = await getDocs(q);
  
  if (snapshot.empty) {
    console.error('Page not found!');
    return;
  }
  
  const pageDoc = snapshot.docs[0];
  let items = pageDoc.data().items || [];
  
  console.log(`Updating item 20: aware-company-award...`);
  
  const updatedItems = items.map(item => {
    if (articles[item.id]) {
      console.log(`  ✓ Updating: ${item.id}`);
      return {
        ...item,
        content: {
          ...item.content,
          ar: articles[item.id]
        }
      };
    }
    return item;
  });
  
  await updateDoc(doc(db, 'pages', pageDoc.id), {
    items: updatedItems,
    updatedAt: new Date().toISOString()
  });
  
  console.log('\n✅ Item 20 for Companies uploaded successfully!');
}

main().catch(console.error);
